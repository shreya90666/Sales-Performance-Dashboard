-- 4. Regional summary view
CREATE OR REPLACE VIEW VW_SALES_SUMMARY AS
SELECT REGION, COUNT(DISTINCT ORDER_ID) TOTAL_ORDERS,
 ROUND(SUM(SALES), 2) TOTAL_SALES,
 ROUND(SUM(PROFIT), 2) TOTAL_PROFIT,
 SUM(QUANTITY) TOTAL_QUANTITY
FROM STG_SUPERSTORE
GROUP BY REGION;

-- 5. Analytics queries
-- Top 10 products
SELECT PRODUCT_NAME, ROUND(SUM(SALES), 2) TOTAL_SALES
FROM STG_SUPERSTORE
GROUP BY PRODUCT_NAME
ORDER BY TOTAL_SALES DESC
FETCH FIRST 10 ROWS ONLY;

-- Monthly sales trend
SELECT EXTRACT(YEAR FROM ORDER_DATE) SALES_YEAR,
 EXTRACT(MONTH FROM ORDER_DATE) SALES_MONTH,
 ROUND(SUM(SALES), 2) TOTAL_SALES
FROM STG_SUPERSTORE
GROUP BY EXTRACT(YEAR FROM ORDER_DATE), EXTRACT(MONTH FROM ORDER_DATE)
ORDER BY SALES_YEAR, SALES_MONTH;

-- Regional sales ranking
SELECT REGION, TOTAL_SALES,
 DENSE_RANK() OVER (ORDER BY TOTAL_SALES DESC) SALES_RANK
FROM (SELECT REGION, ROUND(SUM(SALES), 2) TOTAL_SALES
 FROM STG_SUPERSTORE GROUP BY REGION);

-- Fact/dimension join
SELECT r.REGION, ROUND(SUM(f.SALES), 2) TOTAL_SALES
FROM FACT_SALES f JOIN DIM_REGION r ON f.REGION = r.REGION
GROUP BY r.REGION ORDER BY TOTAL_SALES DESC;

-- Overall KPIs
SELECT ROUND(SUM(SALES), 2) TOTAL_SALES,
 ROUND(SUM(PROFIT), 2) TOTAL_PROFIT,
 COUNT(DISTINCT ORDER_ID) TOTAL_ORDERS,
 SUM(QUANTITY) TOTAL_QUANTITY,
 ROUND(100 * SUM(PROFIT) / NULLIF(SUM(SALES), 0), 2) PROFIT_MARGIN_PERCENT
FROM STG_SUPERSTORE;

-- 6. Final reconciliation (verified in Oracle FreeSQL)
SELECT COUNT(*) TOTAL_ROWS,
 ROUND(SUM(SALES), 2) TOTAL_SALES,
 ROUND(SUM(PROFIT), 2) TOTAL_PROFIT
FROM FACT_SALES;
