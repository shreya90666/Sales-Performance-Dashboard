-- Sales Performance Dashboard | Corrected Oracle SQL
-- Run setup only in a fresh schema after importing superstore_fixed.csv
-- as SUPERSTORE_FIXED. Do not rerun setup in the completed database.
CREATE TABLE STG_SUPERSTORE AS SELECT * FROM SUPERSTORE_FIXED;

CREATE TABLE DIM_REGION AS SELECT DISTINCT REGION FROM STG_SUPERSTORE;
ALTER TABLE DIM_REGION ADD PRIMARY KEY (REGION);
CREATE TABLE DIM_CUSTOMER AS SELECT DISTINCT CUSTOMER_ID, CUSTOMER_NAME, SEGMENT FROM STG_SUPERSTORE;
ALTER TABLE DIM_CUSTOMER ADD PRIMARY KEY (CUSTOMER_ID);
CREATE TABLE DIM_DATE AS SELECT DISTINCT TRUNC(ORDER_DATE) AS DATE_KEY,
 EXTRACT(YEAR FROM ORDER_DATE) AS ORDER_YEAR, EXTRACT(MONTH FROM ORDER_DATE) AS ORDER_MONTH FROM STG_SUPERSTORE;
ALTER TABLE DIM_DATE ADD PRIMARY KEY (DATE_KEY);
CREATE TABLE DIM_PRODUCT AS
SELECT ROW_NUMBER() OVER (ORDER BY PRODUCT_ID, PRODUCT_NAME) AS PRODUCT_KEY,
 PRODUCT_ID, PRODUCT_NAME, CATEGORY, SUB_CATEGORY
FROM (SELECT DISTINCT PRODUCT_ID, PRODUCT_NAME, CATEGORY, SUB_CATEGORY FROM STG_SUPERSTORE);
ALTER TABLE DIM_PRODUCT ADD PRIMARY KEY (PRODUCT_KEY);
ALTER TABLE DIM_PRODUCT ADD CONSTRAINT UQ_PRODUCT UNIQUE (PRODUCT_ID, PRODUCT_NAME);

CREATE TABLE FACT_SALES AS
SELECT s.ROW_ID, s.ORDER_ID, TRUNC(s.ORDER_DATE) AS DATE_KEY,
 s.CUSTOMER_ID, p.PRODUCT_KEY, s.REGION, s.SALES, s.QUANTITY, s.DISCOUNT, s.PROFIT
FROM STG_SUPERSTORE s JOIN DIM_PRODUCT p
ON s.PRODUCT_ID=p.PRODUCT_ID AND s.PRODUCT_NAME=p.PRODUCT_NAME;
ALTER TABLE FACT_SALES ADD PRIMARY KEY (ROW_ID);
ALTER TABLE FACT_SALES ADD FOREIGN KEY (PRODUCT_KEY) REFERENCES DIM_PRODUCT(PRODUCT_KEY);
ALTER TABLE FACT_SALES ADD FOREIGN KEY (CUSTOMER_ID) REFERENCES DIM_CUSTOMER(CUSTOMER_ID);
ALTER TABLE FACT_SALES ADD FOREIGN KEY (REGION) REFERENCES DIM_REGION(REGION);
ALTER TABLE FACT_SALES ADD FOREIGN KEY (DATE_KEY) REFERENCES DIM_DATE(DATE_KEY);

-- Original regional summary view
CREATE OR REPLACE VIEW VW_SALES_SUMMARY AS
SELECT REGION, COUNT(DISTINCT ORDER_ID) TOTAL_ORDERS,
 ROUND(SUM(SALES),2) TOTAL_SALES, ROUND(SUM(PROFIT),2) TOTAL_PROFIT,
 SUM(QUANTITY) TOTAL_QUANTITY FROM STG_SUPERSTORE GROUP BY REGION;

-- Original analytics queries
-- Top 10 products
SELECT PRODUCT_NAME, ROUND(SUM(SALES),2) TOTAL_SALES FROM STG_SUPERSTORE
GROUP BY PRODUCT_NAME ORDER BY TOTAL_SALES DESC FETCH FIRST 10 ROWS ONLY;
-- Monthly trend
SELECT EXTRACT(YEAR FROM ORDER_DATE) SALES_YEAR, EXTRACT(MONTH FROM ORDER_DATE) SALES_MONTH,
 ROUND(SUM(SALES),2) TOTAL_SALES FROM STG_SUPERSTORE
GROUP BY EXTRACT(YEAR FROM ORDER_DATE), EXTRACT(MONTH FROM ORDER_DATE) ORDER BY SALES_YEAR, SALES_MONTH;
-- Regional ranking
SELECT REGION, TOTAL_SALES, DENSE_RANK() OVER (ORDER BY TOTAL_SALES DESC) SALES_RANK
FROM (SELECT REGION, ROUND(SUM(SALES),2) TOTAL_SALES FROM STG_SUPERSTORE GROUP BY REGION);
-- Regional fact/dimension join
SELECT r.REGION, ROUND(SUM(f.SALES),2) TOTAL_SALES FROM FACT_SALES f
JOIN DIM_REGION r ON f.REGION=r.REGION GROUP BY r.REGION ORDER BY TOTAL_SALES DESC;
-- Overall KPIs
SELECT ROUND(SUM(SALES),2) TOTAL_SALES, ROUND(SUM(PROFIT),2) TOTAL_PROFIT,
 COUNT(DISTINCT ORDER_ID) TOTAL_ORDERS, SUM(QUANTITY) TOTAL_QUANTITY,
 ROUND(100*SUM(PROFIT)/NULLIF(SUM(SALES),0),2) PROFIT_MARGIN_PERCENT FROM STG_SUPERSTORE;
-- Fact reconciliation
SELECT COUNT(*) TOTAL_ROWS, ROUND(SUM(SALES),2) TOTAL_SALES, ROUND(SUM(PROFIT),2) TOTAL_PROFIT FROM FACT_SALES;
-- Corrected full join reconciliation
SELECT COUNT(*) TOTAL_ROWS, ROUND(SUM(f.SALES),2) TOTAL_SALES, ROUND(SUM(f.PROFIT),2) TOTAL_PROFIT
FROM FACT_SALES f JOIN DIM_PRODUCT p ON f.PRODUCT_KEY=p.PRODUCT_KEY
JOIN DIM_CUSTOMER c ON f.CUSTOMER_ID=c.CUSTOMER_ID
JOIN DIM_REGION r ON f.REGION=r.REGION JOIN DIM_DATE d ON f.DATE_KEY=d.DATE_KEY;
