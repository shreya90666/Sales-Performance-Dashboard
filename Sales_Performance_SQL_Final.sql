-- Do not rerun CREATE TABLE statements in the existing completed database.

-- 1. Staging table
CREATE TABLE STG_SUPERSTORE (
 ROW_ID NUMBER, ORDER_ID VARCHAR2(30), ORDER_DATE DATE,
 SHIP_DATE DATE, SHIP_MODE VARCHAR2(30), CUSTOMER_ID VARCHAR2(30),
 CUSTOMER_NAME VARCHAR2(120), SEGMENT VARCHAR2(30), COUNTRY VARCHAR2(60),
 CITY VARCHAR2(100), STATE_NAME VARCHAR2(100), POSTAL_CODE VARCHAR2(20),
 REGION VARCHAR2(30), PRODUCT_ID VARCHAR2(40), CATEGORY VARCHAR2(50),
 SUB_CATEGORY VARCHAR2(60), PRODUCT_NAME VARCHAR2(300), SALES NUMBER(14,2),
 QUANTITY NUMBER(10), DISCOUNT NUMBER(6,4), PROFIT NUMBER(14,4),
 ORDER_MONTH DATE, ORDER_YEAR NUMBER(4), PROFIT_MARGIN NUMBER(12,6),
 SHIP_DAYS NUMBER(6)
);

-- Import the 9,994 cleaned rows into STG_SUPERSTORE using Oracle's data loader.

-- 2. Dimensions
CREATE TABLE DIM_REGION AS
SELECT ROW_NUMBER() OVER (ORDER BY REGION) REGION_KEY, REGION
FROM (SELECT DISTINCT REGION FROM STG_SUPERSTORE WHERE REGION IS NOT NULL);

CREATE TABLE DIM_PRODUCT AS
SELECT ROW_NUMBER() OVER (ORDER BY PRODUCT_ID) PRODUCT_KEY,
 PRODUCT_ID, PRODUCT_NAME, CATEGORY, SUB_CATEGORY
FROM (SELECT DISTINCT PRODUCT_ID, PRODUCT_NAME, CATEGORY, SUB_CATEGORY
 FROM STG_SUPERSTORE WHERE PRODUCT_ID IS NOT NULL);

CREATE TABLE DIM_CUSTOMER AS
SELECT ROW_NUMBER() OVER (ORDER BY CUSTOMER_ID) CUSTOMER_KEY,
 CUSTOMER_ID, CUSTOMER_NAME, SEGMENT
FROM (SELECT DISTINCT CUSTOMER_ID, CUSTOMER_NAME, SEGMENT
 FROM STG_SUPERSTORE WHERE CUSTOMER_ID IS NOT NULL);

CREATE TABLE DIM_DATE AS
SELECT ROW_NUMBER() OVER (ORDER BY ORDER_DATE) DATE_KEY,
 ORDER_DATE, EXTRACT(YEAR FROM ORDER_DATE) ORDER_YEAR,
 EXTRACT(MONTH FROM ORDER_DATE) ORDER_MONTH,
 TO_NUMBER(TO_CHAR(ORDER_DATE, 'Q')) ORDER_QUARTER
FROM (SELECT DISTINCT ORDER_DATE FROM STG_SUPERSTORE WHERE ORDER_DATE IS NOT NULL);

-- 3. Sales fact table: full dataset (9,994 records)
CREATE TABLE FACT_SALES AS
SELECT ROW_ID, ORDER_ID, ORDER_DATE, CUSTOMER_ID, PRODUCT_ID,
 REGION, SALES, PROFIT, QUANTITY
FROM STG_SUPERSTORE;

